# make_metrics.R: Helvetica glyph metrics (WinAnsi codes 0-255) for the JS engine ####
#
# Usage: Rscript make_metrics.R engine/metrics.js
# Writes widths, ascents (bbox top) and descents (bbox bottom), in 1/1000 em,
# for fonts 1 plain, 2 bold, 3 italic, 4 bold italic, read from R's AFM files.

afm_dir <- system.file("afm", package = "grDevices")
enc <- readLines(system.file("enc", "WinAnsi.enc", package = "grDevices"))
enc <- paste(enc[!grepl("^%", enc)], collapse = " ")
gnames <- regmatches(enc, gregexpr("/[A-Za-z0-9.]+", enc))[[1]]
gnames <- sub("^/", "", gnames)[-1]
stopifnot(length(gnames) == 256)

read_afm <- function(f) {
  x <- readLines(gzfile(file.path(afm_dir, f)))
  cl <- grep("^C ", x, value = TRUE)
  wx <- as.numeric(sub(".*WX ([0-9.]+).*", "\\1", cl))
  nm <- sub(".* N ([A-Za-z0-9.]+) ;.*", "\\1", cl)
  bb <- sub(".* B (-?[0-9]+) (-?[0-9]+) (-?[0-9]+) (-?[0-9]+).*", "\\2 \\4", cl)
  lly <- as.numeric(sub(" .*", "", bb))
  ury <- as.numeric(sub(".* ", "", bb))
  w <- rep(NA_real_, 256)
  a <- rep(0, 256)
  d <- rep(0, 256)
  for (k in seq_len(256)) {
    hit <- which(nm == gnames[k])
    if (length(hit) > 0) {
      w[k] <- wx[hit[1]]
      a[k] <- ury[hit[1]]
      d[k] <- lly[hit[1]]
    }
  }
  w[is.na(w)] <- wx[nm == "space"][1]
  list(w = w, a = a, d = d)
}

fonts <- c("Helvetica.afm.gz", "Helvetica-Bold.afm.gz", "Helvetica-Oblique.afm.gz", "Helvetica-BoldOblique.afm.gz")
m <- lapply(fonts, read_afm)
row <- function(v) {
  paste0("  [", paste(v, collapse = ","), "],")
}
out <- c("// Generated by tools/make_metrics.R from R's Helvetica AFM files: glyph",
  "// metrics (1/1000 em) for WinAnsi codes 0-255, fonts 1 plain, 2 bold, 3 italic, 4 bold italic.",
  "export const HELV_WIDTHS = [")
for (k in seq_along(m)) {
  out <- c(out, row(m[[k]]$w))
}
out <- c(out, "];", "export const HELV_ASCENT = [")
for (k in seq_along(m)) {
  out <- c(out, row(m[[k]]$a))
}
out <- c(out, "];", "export const HELV_DESCENT = [")
for (k in seq_along(m)) {
  out <- c(out, row(m[[k]]$d))
}
out <- c(out, "];")
writeLines(out, commandArgs(trailingOnly = TRUE)[1])
